/*
|--------------------------------------------------------------------------
| Request Information
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/json_loader.php';

$current_page = basename($_SERVER['SCRIPT_FILENAME'] ?? '');
$seo_page_title_for_header = strtoupper(str_replace(['.php', '-'], ['', ' '], $current_page));

$https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
  || (int) ($_SERVER['SERVER_PORT'] ?? 0) === 443;
$protocol = $https ? 'https://' : 'http://';
$host = $_SERVER['HTTP_HOST'] ?? 'localhost';
$request_uri = $_SERVER['REQUEST_URI'] ?? '/';
$request_path = parse_url($request_uri, PHP_URL_PATH) ?: '/';

// $base_url is initialized by variables_global.php before this file.
$site_url = rtrim($base_url ?? ($protocol . $host), '/');
$seo_canonical_url = $protocol . $host . $request_path;

/*
|--------------------------------------------------------------------------
| Defaults
|--------------------------------------------------------------------------
*/

$seo_page_title = '';
$seo_description = '';
$seo_og_img = '';
$seo_alt_lang_de = '';
$seo_alt_lang_en = '';
$seo_type = 'WebPage';
$breadcrumb_position = 2;
$breadcrumb_item = $seo_canonical_url;

/*
|--------------------------------------------------------------------------
| SEO for regular pages
|--------------------------------------------------------------------------
*/

foreach ($seo_page_array as $seo_page) {
  if ($seo_page['page_name'] !== $current_page || $seo_page['lang'] !== $lang) {
    continue;
  }

  if ($current_page !== 'post.php') {
    $seo_page_title = $seo_page['seo_page_title'];
    $seo_description = $seo_page['seo_description'];
    $seo_og_img = !empty($seo_page['seo_img'])
      ? $site_url . '/misc/seo/' . $seo_page['seo_img']
      : '';
    $breadcrumb_position = $seo_page['breadcrumb_position'] ?? 2;
    $breadcrumb_item = $seo_canonical_url;
    $seo_alt_lang_de = $seo_page['seo_alt_lang_de'];
    $seo_alt_lang_en = $seo_page['seo_alt_lang_en'];
    $seo_type = $seo_page['seo_type'];
  }

  break;
}

/*
|--------------------------------------------------------------------------
| SEO for blog posts: use the same JSON content as the blog component
|--------------------------------------------------------------------------
*/

if ($current_page === 'post.php') {
  $blog_language = $lang === 'de' ? 'de' : 'en';
  $blog_json_path = __DIR__ . '/../components/blog/content/blog_content_'
    . $blog_language . '.json';

  $seo_blog_entries = loadJsonContent($blog_json_path);

  // mod_rewrite provides seo_url for /de/post/example and /en/post/example.
  $post_slug = $_GET['seo_url'] ?? '';

  // Also handle clean URLs when the query parameter is unavailable.
  if ($post_slug === '' && preg_match('~/(?:de|en)/post/([^/]+)/?$~', $request_path, $matches)) {
    $post_slug = rawurldecode($matches[1]);
  }

  $matched = false;

  foreach ($seo_blog_entries as $blog_entry) {
    if (($blog_entry['seo_url'] ?? '') !== $post_slug) {
      continue;
    }

    $seo = $blog_entry['seo'] ?? [];
    $seo_page_title = $seo['seo_page_title'] ?? $blog_entry['title'] ?? 'Post';
    $seo_description = $seo['seo_description'] ?? '';
    $seo_img = $seo['seo_img'] ?? $blog_entry['picture'] ?? '';
    $seo_og_img = $seo_img !== ''
      ? $site_url . '/components/blog/img/' . $seo_img
      : '';
    $breadcrumb_position = $seo['post_breadcrumb_position'] ?? 3;
    $breadcrumb_item = $seo_canonical_url;
    $seo_alt_lang_de = $seo['seo_alt_lang_de'] ?? '';
    $seo_alt_lang_en = $seo['seo_alt_lang_en'] ?? '';
    $seo_type = $seo['seo_type'] ?? 'BlogPosting';

    if (!empty($seo['org_title']) && !empty($seo['org_artist'])) {
      $org_title = $seo['org_title'];
      $org_artist = $seo['org_artist'];
    }

    $matched = true;
    break;
  }

  if (!$matched) {
    $seo_page_title = 'Post';
    $seo_description = 'Post';
    $seo_og_img = $site_url . '/components/blog/img/default_post_page.jpg';
    $breadcrumb_position = 2;
    $breadcrumb_item = $site_url . '/' . $blog_language . '/blog';
    $seo_alt_lang_de = '';
    $seo_alt_lang_en = '';
    $seo_type = 'WebPage';
  }
}

